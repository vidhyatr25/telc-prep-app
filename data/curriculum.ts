export interface VocabItem {
  german: string;
  english: string;
  article?: string; // der/die/das
  example?: string;
  exampleEn?: string;
}

export interface GrammarRule {
  title: string;
  explanation: string;
  examples: { german: string; english: string }[];
}

export interface Lesson {
  id: string;
  title: string;
  titleDe: string;
  type: "vocab" | "grammar" | "dialogue" | "reading";
  content: string;
  contentDe?: string;
  vocab?: VocabItem[];
  grammar?: GrammarRule[];
  dialogue?: { speaker: string; line: string; lineDe?: string }[];
  xp: number;
}

export interface QuizQuestion {
  id: string;
  type: "multiple-choice" | "true-false" | "fill-blank" | "match";
  question: string;
  questionDe?: string;
  options?: string[];
  answer: string | number;
  explanation?: string;
}

export interface Unit {
  id: number;
  slug: string;
  title: string;
  titleDe: string;
  description: string;
  descriptionDe: string;
  icon: string;
  color: string;
  lessons: Lesson[];
  quiz: QuizQuestion[];
  xpReward: number;
}

